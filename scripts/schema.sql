BEGIN;
CREATE TABLE IF NOT EXISTS settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  data jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS owner_account (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  password_hash text NOT NULL
);
CREATE TABLE IF NOT EXISTS owner_sessions (
  digest text PRIMARY KEY,
  expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
  id uuid PRIMARY KEY,
  number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  idem_digest text NOT NULL UNIQUE,
  token text NOT NULL UNIQUE,
  items jsonb NOT NULL,
  contact jsonb NOT NULL,
  snapshot jsonb NOT NULL,
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'agreed', 'done', 'canceled')),
  final_price integer CHECK (final_price >= 0),
  agreed_date text NOT NULL DEFAULT '',
  agreed_time text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  history jsonb NOT NULL DEFAULT '[]'::jsonb,
  bonus jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status <> 'agreed' OR (final_price IS NOT NULL AND agreed_date <> '' AND agreed_time <> ''))
);
CREATE INDEX IF NOT EXISTS orders_status_created ON orders(status, created_at DESC);
CREATE TABLE IF NOT EXISTS photos (
  id uuid PRIMARY KEY,
  draft_digest text NOT NULL,
  order_id uuid REFERENCES orders(id) ON DELETE CASCADE,
  data bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS photos_draft ON photos(draft_digest) WHERE order_id IS NULL;
CREATE INDEX IF NOT EXISTS photos_order ON photos(order_id) WHERE order_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS rate_limits (
  bucket text PRIMARY KEY,
  count integer NOT NULL,
  ends_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS removed_requests (
  digest text PRIMARY KEY
);

COMMIT;
